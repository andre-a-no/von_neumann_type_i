#!/usr/bin/env python3
"""
Chains of SU(2)_k anyons and their conformal data (man/article, Section "Anyonic chains and Temperley-Lieb algebras",
sec:anyons).

For k = 2, 3, 4 (Ising, tricritical Ising = golden chain, tetracritical Ising) the script computes with the library
alone (AnyonChain, krylov.ground_state):
  * the central charge from periodic chains, E0(L) = e L - pi v c/(6 L) + a/L^3, with the exact velocity
    v = pi sin(gamma)/gamma, gamma = pi/(k+2), fitted on the largest sizes;
  * the velocity from open chains, v(L) = L (E1 - E0)/(2 pi) in the sector b = 0 (first descendant at level 2),
    extrapolated in 1/L;
  * the ratio (E0(b=2) - E0(b=0))/(E1(b=0) - E0(b=0)) of open chains, extrapolated in 1/L, against the Kac value
    h_{1,3}/2 of the boundary condition (0, b);
  * the Jones index of TL_{L-1} c TL_L against 4 cos^2(pi/(k+2)).
Writes generated/anyon_chain.{tex,json} (macros \\AC...).
"""
import json
import math
import time
from pathlib import Path

import numpy as np
import torch

from common import environment
from torch_vn_algebra import AnyonChain

OUT = Path(__file__).resolve().parents[1] / 'man' / 'article' / 'generated'
SIZES = {2: (range(10, 23, 2), range(10, 25, 2)),       # periodic, open
         3: (range(10, 23, 2), range(10, 25, 2)),
         4: (range(8, 19, 2), range(8, 21, 2))}
NAMES = {2: 'Ising', 3: 'tricritical Ising', 4: 'tetracritical Ising'}


def extrapolate(L, y, n=5):
    A = np.stack([np.ones_like(L), 1 / L, 1 / L ** 2], 1)[-n:]
    return float(np.linalg.lstsq(A, y[-n:], rcond=None)[0][0])


def main():
    torch.set_num_threads(4)
    t0 = time.time()
    rows, res = [], {}
    for k, (per, opn) in SIZES.items():
        Lp = np.array(list(per), float)
        E0p = np.array([float(AnyonChain(k, int(L), periodic=True).low_energies()[0][0]) for L in Lp])
        co = np.linalg.lstsq(np.stack([Lp, 1 / Lp, 1 / Lp ** 3], 1)[-5:], E0p[-5:], rcond=None)[0]
        c = -co[1] * 6 / (math.pi * AnyonChain.velocity(k))
        Lo = np.array(list(opn), float)
        E0, E1, E2 = [], [], []
        for L in Lo:
            e = AnyonChain(k, int(L)).low_energies(levels=2)
            E0.append(float(e[0][0])); E1.append(float(e[0][1])); E2.append(float(e[1][0]))
        E0, E1, E2 = map(np.array, (E0, E1, E2))
        v = extrapolate(Lo, Lo * (E1 - E0) / (2 * math.pi))
        R = extrapolate(Lo, (E2 - E0) / (E1 - E0))
        idx = AnyonChain(k, max(k + 2, 6)).inclusion().index()
        r = dict(c=c, c_exact=AnyonChain.central_charge(k), e_inf=float(co[0]), v=v, v_exact=AnyonChain.velocity(k),
                 ratio=R, ratio_exact=AnyonChain.kac(k, 1, 3) / 2, index=idx,
                 index_exact=(2 * math.cos(math.pi / (k + 2))) ** 2,
                 Lmax_periodic=int(Lp[-1]), Lmax_open=int(Lo[-1]),
                 dim_periodic=AnyonChain(k, int(Lp[-1]), periodic=True).algebra.k_max)
        res[k] = r
        rows.append(f"{k} & {NAMES[k]} & {r['c_exact']:.4f} & {c:.4f} & {r['ratio_exact']:.4f} & {R:.4f} & "
                    f"{r['v_exact']:.4f} & {v:.4f} & {idx:.4f}\\\\")
        print(k, r)
    seconds = time.time() - t0
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / 'anyon_chain.json').write_text(json.dumps(dict(results=res, seconds=seconds, threads=torch.get_num_threads(),
                                                          environment=environment('cpu')), indent=2, default=float))
    gold = res[3]
    tex = ['% generated by scripts/anyon_chain.py -- do not edit by hand', '\\newcommand{\\ACRows}{%', *rows, '}',
           f"\\newcommand{{\\ACGoldenC}}{{{gold['c']:.4f}}}",
           f"\\newcommand{{\\ACGoldenE}}{{{gold['e_inf']:.7f}}}",
           f"\\newcommand{{\\ACGoldenDim}}{{{gold['dim_periodic']}}}",
           f"\\newcommand{{\\ACGoldenL}}{{{gold['Lmax_periodic']}}}",
           f"\\newcommand{{\\ACSeconds}}{{{seconds:.0f}}}",
           f"\\newcommand{{\\ACThreads}}{{{torch.get_num_threads()}}}"]
    (OUT / 'anyon_chain.tex').write_text('\n'.join(tex) + '\n')


if __name__ == '__main__':
    main()
