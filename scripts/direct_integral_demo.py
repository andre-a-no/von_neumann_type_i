#!/usr/bin/env python3
"""
A continuous centre, discretised (man/article, Section "Continuous centres: direct integrals", sec:integral).

The SSH chain has the Bloch Hamiltonian H(k) = [[0, 1 + t e^{-ik}], [1 + t e^{ik}, 0]]; the translation-invariant
observables form the direct integral of M_2 over the Brillouin zone with dk/2pi, and the ground-state energy per cell is
int Tr min(H(k), 0) dk/2pi = -(2/pi)(1 + t) E(4t/(1 + t)^2) (complete elliptic integral E). DirectIntegral.torus(n)
discretises the zone by the n momenta of a periodic chain of n cells, one 2x2 sector each. The script reports the
error of this rule for a gapped (t = 0.5) and the gapless (t = 1) chain, the root-mean-square error of Monte Carlo
nodes, and the time for 10^5 nodes on the CPU. Writes generated/direct_integral.{tex,json} (macros \\DI...).
"""
import json
import math
import time
from pathlib import Path

import torch
from scipy.special import ellipe

from common import environment                        # device, versions, matmul precision, commit
from torch_vn_algebra import DirectIntegral

OUT = Path(__file__).resolve().parents[1] / 'man' / 'article' / 'generated'
NS = [8, 16, 32, 64, 128, 256]


def ssh(t):
    def f(k):
        z = 1 + t * torch.exp(1j * k[:, 0])
        H = torch.zeros(k.shape[0], 2, 2, dtype=torch.complex128)
        H[:, 0, 1], H[:, 1, 0] = z.conj(), z
        return H
    return f


def exact(t):
    return -2 / math.pi * (1 + t) * ellipe(4 * t / (1 + t) ** 2)


def energy(X, t):
    H = X.field(ssh(t), is_self_adjoint=True)
    return float(X.trace(H.apply_function(lambda w: w.clamp(max=0))).real)


def sci(x):
    if x < 1e-15:
        return '<10^{-15}'
    m, e = f"{x:.1e}".split('e')
    return f"{m}{{\\times}}10^{{{int(e)}}}"


def main():
    torch.set_num_threads(4)
    rows, res = [], {}
    for n in NS:
        X = DirectIntegral.torus(n, dims=2)
        e = {t: abs(energy(X, t) - exact(t)) for t in (0.5, 1.0)}
        res[n] = e
        rows.append(f"{n} & ${sci(e[0.5])}$ & ${sci(e[1.0])}$\\\\")
    slope = math.log(res[NS[-2]][1.0] / res[NS[-1]][1.0]) / math.log(NS[-1] / NS[-2])
    mc_nodes, seeds = 10000, 20
    errs = []
    for s in range(seeds):
        g = torch.Generator().manual_seed(s)
        X = DirectIntegral.monte_carlo(lambda m, gen: 2 * math.pi * torch.rand(m, generator=gen, dtype=torch.float64),
                                       mc_nodes, dims=2, generator=g)
        errs.append(energy(X, 0.5) - exact(0.5))
    mc_rms = math.sqrt(sum(x * x for x in errs) / seeds)
    big = 100000
    X = DirectIntegral.torus(big, dims=2)
    energy(X, 0.5)                                      # warm-up
    t0 = time.time()
    e_big = energy(X, 0.5)
    seconds = time.time() - t0
    payload = dict(n=NS, err_gapped=[res[n][0.5] for n in NS], err_gapless=[res[n][1.0] for n in NS],
                   gapless_slope=slope, mc_nodes=mc_nodes, mc_seeds=seeds, mc_rms=mc_rms, big_nodes=big,
                   big_seconds=seconds, big_error=abs(e_big - exact(0.5)), threads=torch.get_num_threads(),
                   environment=environment('cpu'))
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / 'direct_integral.json').write_text(json.dumps(payload, indent=2, default=float))
    tex = ['% generated by scripts/direct_integral_demo.py -- do not edit by hand',
           '\\newcommand{\\DIRows}{%', *rows, '}',
           f'\\newcommand{{\\DISlope}}{{{slope:.2f}}}',
           f'\\newcommand{{\\DIMCNodes}}{{10^{{{int(round(math.log10(mc_nodes)))}}}}}',
           f'\\newcommand{{\\DIMCSeeds}}{{{seeds}}}',
           f'\\newcommand{{\\DIMCErr}}{{{sci(mc_rms)}}}',
           f'\\newcommand{{\\DIBigNodes}}{{10^{{{int(round(math.log10(big)))}}}}}',
           f'\\newcommand{{\\DIBigTime}}{{{seconds:.2f}}}',
           f'\\newcommand{{\\DIThreads}}{{{torch.get_num_threads()}}}']
    (OUT / 'direct_integral.tex').write_text('\n'.join(tex) + '\n')
    print(json.dumps({k: v for k, v in payload.items() if k != 'environment'}, indent=1, default=float))


if __name__ == '__main__':
    main()
