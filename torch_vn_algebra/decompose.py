def permutation_representation(n_sites: int, local_dim: int = 2,
                               permutations: Union[str, Sequence[Sequence[int]]] = 'all',
                               dtype: torch.dtype = torch.complex128, device=None) -> torch.Tensor:
    r"""
    The representation of the symmetric group :math:`S_L` permuting the tensor factors of
    :math:`(\mathbb C^d)^{\otimes L}`:
    :math:`\pi(\sigma)(v_0\otimes\dots\otimes v_{L-1})=v_{\sigma^{-1}(0)}\otimes\dots\otimes v_{\sigma^{-1}(L-1)}`,
    i.e. the vector in slot i moves to slot sigma(i); it is a homomorphism,
    :math:`\pi(\sigma\tau)=\pi(\sigma)\pi(\tau)` with :math:`(\sigma\tau)(i)=\sigma(\tau(i))`.

    n_sites: L; local_dim: d. The basis is the Kronecker one (site 0 most significant, as torch.kron).
    permutations: 'all' (the L! elements of S_L, in itertools.permutations order: for from_group),
        'adjacent' (the L - 1 transpositions (i, i+1), which generate S_L: for from_generators), or a list
        of permutations in one-line notation (p[i] = sigma(i), 0-based).
    Returns a real-valued tensor (P, d^L, d^L) of permutation matrices in ``dtype``.
    """
    L, d = int(n_sites), int(local_dim)
    if L < 1 or d < 1:
        raise ValueError("need n_sites >= 1 and local_dim >= 1")
    if permutations == 'all':
        perms = list(itertools.permutations(range(L)))
    elif permutations == 'adjacent':
        perms = [tuple(i + 1 if t == i else i if t == i + 1 else t for t in range(L)) for i in range(L - 1)] \
            or [tuple(range(L))]
    else:
        perms = [tuple(int(x) for x in p) for p in permutations]
        for p in perms:
            if sorted(p) != list(range(L)):
                raise ValueError(f"{p} is not a permutation of 0..{L - 1}")
    D = d ** L
    eye = torch.eye(D, dtype=dtype, device=device).reshape((d,) * L + (D,))
    out = []
    for p in perms:
        inv = [0] * L
        for i, pi in enumerate(p):
            inv[pi] = i
        out.append(eye.permute(*inv, L).reshape(D, D))
    return torch.stack(out)


def collective_operators(local_ops: MatrixLike, n_sites: int) -> torch.Tensor:
    r"""
    Diagonal (collective) action of local operators on :math:`(\mathbb C^d)^{\otimes L}`:
    :math:`X\mapsto\sum_{i}1\otimes\dots\otimes X_{(i)}\otimes\dots\otimes1`, the derivative of
    :math:`g\mapsto g^{\otimes L}`; for Lie algebra generators X_a of a group acting on C^d these are the
    generators of the diagonal action. local_ops: (J, d, d) or list; returns (J, d^L, d^L).
    """
    X = _stack(local_ops, "local_ops")
    J, d = X.shape[0], X.shape[-1]
    L = int(n_sites)
    out = torch.zeros(J, d ** L, d ** L, dtype=X.dtype, device=X.device)
    for i in range(L):
        left = torch.eye(d ** i, dtype=X.dtype, device=X.device)
        right = torch.eye(d ** (L - 1 - i), dtype=X.dtype, device=X.device)
        out += torch.stack([torch.kron(torch.kron(left, x), right) for x in X])
    return out


def spin_matrices(spin: float = 0.5, dtype: torch.dtype = torch.complex128, device=None) -> torch.Tensor:
    """Spin operators (S_x, S_y, S_z) of spin s in the basis m = s, s-1, ..., -s: (3, 2s+1, 2s+1)."""
    d = int(round(2 * spin)) + 1
    if d < 1 or abs((d - 1) / 2 - spin) > 1e-12:
        raise ValueError("spin must be a non-negative half-integer")
    m = torch.tensor([spin - a for a in range(d)], dtype=torch.float64)
    sp = torch.zeros(d, d, dtype=torch.float64)
    for a in range(1, d):                                   # S_+ |m> = sqrt(s(s+1) - m(m+1)) |m+1>
        sp[a - 1, a] = math.sqrt(spin * (spin + 1) - m[a] * (m[a] + 1))
    sp = sp.to(dtype=dtype, device=device)
    sx = (sp + sp.mH) / 2
    sy = (sp - sp.mH) / 2j
    sz = torch.diag(m).to(dtype=dtype, device=device)
    return torch.stack([sx, sy, sz])


def total_spin(n_sites: int, spin: float = 0.5, dtype: torch.dtype = torch.complex128, device=None) -> torch.Tensor:
    r"""
    Total spin :math:`S_a=\sum_i s_a^{(i)}` (a = x, y, z) on :math:`(\mathbb C^{2s+1})^{\otimes L}`:
    (3, D, D) with D = (2s+1)^L, the generators of the diagonal SU(2) action. By Schur-Weyl duality
    (Fulton-Harris Sec. 6.1) the algebra they generate is the commutant of the permutation algebra:
    for s = 1/2, ``from_generators(total_spin(L))`` has k = 2J + 1 (total spin J) and m = dimension of
    the S_L irrep of the two-row partition (L/2 + J, L/2 - J).
    """
    return collective_operators(spin_matrices(spin, dtype, device), n_sites)
