class _BasisSampler:
    """Random elements of the commutant from a basis (d, n, n)."""

    def __init__(self, basis: torch.Tensor, gen: torch.Generator):
        self.basis, self.gen = basis, gen
        self.dim = basis.shape[0]

    def _draw(self) -> torch.Tensor:
        c = _randn((self.dim,), self.basis.dtype, self.basis.device, self.gen)
        return torch.einsum('d,dij->ij', c, self.basis)

    def general(self) -> torch.Tensor:
        """A Gaussian element of the commutant, unit Frobenius norm."""
        return _normalised(self._draw())

    def hermitian(self) -> torch.Tensor:
        """A Gaussian Hermitian element of the commutant (A' is *-closed), unit Frobenius norm."""
        Y = self._draw()
        return _normalised(Y + Y.mH)


class _TwirlSampler:
    """Random elements of pi(G)' as twirls of Gaussian matrices (no basis of the commutant)."""

    def __init__(self, G: torch.Tensor, gen: torch.Generator, dim: int):
        self.G, self.gen, self.dim = G, gen, dim

    def _draw(self) -> torch.Tensor:
        n = self.G.shape[-1]
        return twirl(self.G, _randn((n, n), self.G.dtype, self.G.device, self.gen))

    def general(self) -> torch.Tensor:
        """The twirl of a Ginibre matrix, unit Frobenius norm."""
        return _normalised(self._draw())

    def hermitian(self) -> torch.Tensor:
        """The twirl of a Hermitian Gaussian matrix (the twirl commutes with the adjoint), unit norm."""
        Y = self._draw()
        return _normalised(Y + Y.mH)


