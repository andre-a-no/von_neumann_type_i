def _probe(Hs: torch.Tensor, gen: torch.Generator) -> torch.Tensor:
    """A random Hermitian element of the algebra generated by the Hermitian matrices Hs (J, n, n):
    a random combination plus a random multiple of a symmetrised product of two random combinations
    (the product breaks the degeneracies of linear combinations of Lie algebra generators)."""
    J = Hs.shape[0]
    rdt = Hs.real.dtype
    c = _randn((3, J), rdt, Hs.device, gen).to(Hs.dtype)
    Y = _normalised(torch.einsum('rj,jab->rab', c, Hs))
    P = Y[1] @ Y[2]
    P = _normalised(P + P.mH)
    a = _randn((1,), rdt, Hs.device, gen).to(Hs.dtype)
    return Y[0] + a * P


def _nullspace_commutant(Hs: torch.Tensor, tol: float, gen: torch.Generator, n: int, dtype, device) -> \
        Tuple[torch.Tensor, Dict]:
    """Orthonormal basis (d, n, n) of {Hs}' by the reduced null-space method (module docstring)."""
    eps = _eps(dtype)
    if Hs.shape[0] == 0:                                    # only multiples of 1: the commutant is M_n
        cost.check_memory(cost.tensor_bytes((n * n, n, n), dtype), device, f"commutant_basis (M_{n})")
        basis = torch.eye(n * n, dtype=dtype, device=device).reshape(n * n, n, n)
        return basis, dict(method='nullspace', unknowns=n * n, threshold=0.0, sigma=None)
    R = _probe(Hs, gen)
    w, U = torch.linalg.eigh(R)
    bounds = _gap_clusters(w, eps ** 0.25, 1e3 * n * eps)
    lab = torch.empty(n, dtype=torch.long, device=device)
    for c, (s, e) in enumerate(bounds):
        lab[s:e] = c
    r_idx, q_idx = (lab[:, None] == lab[None, :]).nonzero(as_tuple=True)
    N = r_idx.numel()
    ar = torch.arange(N, device=device)
    cost.check_memory(2 * cost.tensor_bytes((n * n + N, N), dtype), device,
                      f"commutant_basis (null space, n={n}, {N} unknowns)")
    Ht = U.mH @ Hs @ U                                       # generators in the eigenbasis of the probe
    Rfac = torch.zeros(0, N, dtype=dtype, device=device)
    for H in Ht:
        L = torch.zeros(n, n, N, dtype=dtype, device=device)
        L[:, q_idx, ar] = H[:, r_idx]                         # H E_rq
        L[r_idx, :, ar] -= H[q_idx, :]                        # - E_rq H
        Rfac = torch.linalg.qr(torch.cat([Rfac, L.reshape(n * n, N)]), mode='r')[1]
    s, Vh = torch.linalg.svd(Rfac)[1:]
    smax = float(s[0]) if s.numel() else 0.0
    thr = tol * max(1.0, smax)
    rank = int((s > thr).sum())
    null = Vh[rank:].conj()                                  # R is N x N (n^2 >= N rows were factorised)
    d = null.shape[0]
    Xt = torch.zeros(d, n, n, dtype=dtype, device=device)
    Xt[:, r_idx, q_idx] = null
    basis = U @ Xt @ U.mH
    gray = eps ** (-0.125)
    near = ((s > thr / gray) & (s < thr * gray)).sum()
    info = dict(method='nullspace', unknowns=N, clusters=len(bounds), threshold=thr, sigma_max=smax,
                sigma_null_max=float(s[rank:].max()) if rank < N else 0.0,
                sigma_kept_min=float(s[rank - 1]) if rank else float('inf'))
    if int(near):
        warnings.warn(f"commutant_basis: {int(near)} singular value(s) of the commutator map lie within a "
                      f"factor {gray:.0f} of the rank threshold {thr:.1e} (largest null {info['sigma_null_max']:.1e},"
                      f" smallest kept {info['sigma_kept_min']:.1e}); the commutant dimension is ill-determined, "
                      "pass an explicit tol", DecompositionWarning, stacklevel=3)
    return basis, info


def _twirl_commutant(G: torch.Tensor, d: int, gen: torch.Generator, tol: float) -> Tuple[torch.Tensor, Dict]:
    """Orthonormal basis (d, n, n) of pi(G)' as the range of the twirl applied to d + 8 Gaussian matrices."""
    n = G.shape[-1]
    r = d + 8
    X = twirl(G, _randn((r, n, n), G.dtype, G.device, gen))
    M = X.reshape(r, n * n)
    _, s, Vh = torch.linalg.svd(M, full_matrices=False)
    if s.numel() < d or float(s[d - 1]) <= tol * float(s[0]) or (s.numel() > d and float(s[d]) > tol * float(s[0])):
        raise ValueError("commutant_basis(method='twirl'): the twirl does not have rank |G|^-1 sum |tr g|^2; "
                         "the matrices are not all elements of a unitary group representation")
    return Vh[:d].reshape(d, n, n), dict(method='twirl', samples=r,
                                         sigma_ratio=float(s[d - 1] / s[0]),
                                         sigma_null_max=float(s[d] / s[0]) if s.numel() > d else 0.0)


def commutant_basis(generators: MatrixLike, tol: Optional[float] = None, *, group: bool = False,
                    method: str = 'auto', seed: Optional[int] = 0, precision: Optional[str] = None,
                    return_info: bool = False):
    r"""
    Orthonormal (Hilbert-Schmidt) basis of the commutant
    :math:`S'=\{X\in M_n: XS=SX,\ XS^*=S^*X\ \forall S\in\text{generators}\}`.

    generators: (J, n, n) tensor or list of (n, n) matrices (real or complex; not necessarily
        Hermitian or *-closed: the adjoints are included).
    tol: relative singular-value threshold of the null space (default sqrt(eps) of the precision).
    group: True if the matrices are *all* elements of a unitary representation of a finite group;
        enables the twirl method.
    method: 'nullspace' (null space of X -> ([H_j, X])_j after the reduction by a random element of
        the algebra; O(n^3 + J n^2 N^2) with N = sum_c k_c m_c^2 for a generic probe, n^6 at worst),
        'twirl' (group only: range of the twirl of d + 8 random matrices, d from the characters;
        O(d |G| n^3)), or 'auto': the twirl for a group when d |G| <= n^2, otherwise the null space;
        for a group the null space uses three random elements of span pi(G) = A as generators and
        its dimension is checked against the characters (falling back to the twirl).
    seed: seed of the random probe (the span does not depend on it); None for fresh entropy.
    precision: 'double' or 'single' (default: from the input dtype).
    return_info: also return a dict of diagnostics (method, singular values at the threshold).

    Returns a tensor (d, n, n) with tr(B_a^* B_b) = delta_ab (complex dtype), and the info dict if asked.
    """
    S0 = _stack(generators)
    precision, dtype = _work_dtype(S0, precision)
    S = S0.to(dtype)
    n, device = S.shape[-1], S.device
    eps = _eps(dtype)
    tol = eps ** 0.5 if tol is None else float(tol)
    gen = _rng(seed, device)
    if method not in ('auto', 'nullspace', 'twirl'):
        raise ValueError("method must be 'auto', 'nullspace' or 'twirl'")
    if method == 'twirl' and not group:
        raise ValueError("method='twirl' needs group=True (all elements of a finite group)")
    if group:
        _check_unitary_group(S, tol)
        d = commutant_dimension(S)
        use_twirl = method == 'twirl' or (method == 'auto' and (d + 8) * S.shape[0] <= n * n)
        if not use_twirl:
            c = _randn((3, S.shape[0]), dtype, device, gen)
            Hs = _normalised(torch.einsum('rg,gab->rab', c, S))
            Hs = _normalised(torch.cat([Hs + Hs.mH, (Hs - Hs.mH) / 1j]))
            basis, info = _nullspace_commutant(Hs, tol, gen, n, dtype, device)
            if basis.shape[0] == d:
                return (basis, info) if return_info else basis
        basis, info = _twirl_commutant(S, d, gen, tol)
        return (basis, info) if return_info else basis
    if method == 'twirl':
        raise ValueError("method='twirl' needs group=True")
    basis, info = _nullspace_commutant(_hermitian_parts(S, tol), tol, gen, n, dtype, device)
    return (basis, info) if return_info else basis


