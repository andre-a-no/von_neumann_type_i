def twirl(group: MatrixLike, X: torch.Tensor) -> torch.Tensor:
    r"""
    Group average :math:`P(X)=|G|^{-1}\sum_g\pi(g)X\pi(g)^*`.

    For a unitary representation given by all its elements, P is the orthogonal (Hilbert-Schmidt)
    projection of :math:`M_n` onto the commutant :math:`\pi(G)'` (course, Sec. 2.4).

    group: (|G|, n, n) or a list of matrices, all elements of the group.
    X: (n, n) or (B, n, n). Returns a tensor of the shape of X (dtype promoted with the group's).
    Cost O(|G| B n^3); the sum runs over chunks of group elements, memory O(B n^2 * chunk).
    """
    G = _stack(group, "group")
    squeeze = X.dim() == 2
    Xb = X.unsqueeze(0) if squeeze else X
    dt = torch.promote_types(G.dtype, Xb.dtype)
    G, Xb = G.to(dt), Xb.to(device=G.device, dtype=dt)
    B, n = Xb.shape[0], Xb.shape[-1]
    chunk = max(1, 2 ** 24 // max(1, B * n * n))
    out = torch.zeros_like(Xb)
    for s in range(0, G.shape[0], chunk):
        g = G[s:s + chunk].unsqueeze(1)                        # (c, 1, n, n)
        out += (g @ Xb.unsqueeze(0) @ g.mH).sum(0)
    out /= G.shape[0]
    return out[0] if squeeze else out


def commutant_dimension(group: MatrixLike) -> int:
    r"""
    :math:`\dim\pi(G)'=|G|^{-1}\sum_g|\operatorname{tr}\pi(g)|^2=\sum_cm_c^2` (orthogonality of
    characters), for a unitary representation given by all group elements, (|G|, n, n).
    Raises ValueError if the value is not an integer (the matrices are not all elements of a unitary
    representation).
    """
    G = _stack(group, "group")
    Gd = G.to(torch.complex128) if G.dtype in (torch.complex64, torch.complex128) else G.to(torch.float64)
    chi = torch.diagonal(Gd, dim1=-2, dim2=-1).sum(-1)
    val = float((chi.abs() ** 2).mean())
    d = round(val)
    if d < 1 or abs(val - d) > 1e-6 * max(1.0, val) + 1e3 * _eps(Gd.dtype) * G.shape[-1] ** 2:
        raise ValueError(f"commutant_dimension: |G|^-1 sum |tr g|^2 = {val:.6g} is not a positive integer; "
                         "the matrices are not all elements of a unitary group representation")
    return d


def _check_unitary_group(G: torch.Tensor, tol: float):
    n = G.shape[-1]
    eye = torch.eye(n, dtype=G.dtype, device=G.device)
    err = float((G.mH @ G - eye).abs().amax())
    if err > tol:
        raise ValueError(f"group elements must be unitary (max |g^* g - 1| = {err:.2e}); "
                         "unitarise the representation first (e.g. Weyl's trick)")


