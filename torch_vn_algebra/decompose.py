def _sector_maps(ks: Sequence[int], ms: Sequence[int], n: int, side: str, device):
    """
    Index maps between the n x n matrix V^* a V and the padded blocks (C, s_max, s_max) of one side.
    side='algebra': block entry (c, i, i') <- mean_j (V^* a V)[off_c + i m_c + j, off_c + i' m_c + j];
    side='commutant': block entry (c, j, j') <- mean_i (V^* a V)[off_c + i m_c + j, off_c + i m_c + j'].
    Returns (flat index p*n + q into the n x n matrix, flat index into (C, s_max, s_max), weight).
    """
    smax = max(ks) if side == 'algebra' else max(ms)
    pq, src, w = [], [], []
    off = 0
    for c, (k, m) in enumerate(zip(ks, ms)):
        if side == 'algebra':
            i, ip, j = torch.meshgrid(torch.arange(k), torch.arange(k), torch.arange(m), indexing='ij')
            p, q = off + i * m + j, off + ip * m + j
            s, weight = c * smax * smax + i * smax + ip, 1.0 / m
        else:
            j, jp, i = torch.meshgrid(torch.arange(m), torch.arange(m), torch.arange(k), indexing='ij')
            p, q = off + i * m + j, off + i * m + jp
            s, weight = c * smax * smax + j * smax + jp, 1.0 / k
        pq.append((p * n + q).flatten())
        src.append(s.flatten())
        w.append(torch.full((p.numel(),), weight, dtype=torch.float64))
        off += k * m
    return torch.cat(pq).to(device), torch.cat(src).to(device), torch.cat(w).to(device)


def _takagi_unitary(U: torch.Tensor, gen: torch.Generator, tries: int = 3) -> Tuple[torch.Tensor, float]:
    r"""
    W unitary with :math:`U=WW^T` for a symmetric unitary U (Autonne-Takagi factorisation with unit singular
    values). Re U and Im U are commuting real symmetric matrices (U^{-1} = U^* = conj(U) for U = U^T); an
    orthogonal O diagonalising Re U + t Im U for a random t diagonalises both, U = O diag(d) O^T with |d| = 1,
    and W = O diag(sqrt d). Returns (W, residual ||W W^T - U||_F / ||U||_F).
    """
    k = U.shape[-1]
    best = None
    for _ in range(tries):
        t = float(torch.rand((), generator=gen, device=gen.device)) * 2.0 + 0.5
        _, O = torch.linalg.eigh(U.real + t * U.imag)
        O = O.to(U.dtype)
        d = torch.diagonal(O.mT @ U @ O)
        W = O * torch.sqrt(d / d.abs())[None, :]
        res = float(_fro(W @ W.mT - U) / max(float(_fro(U)), 1e-300))
        if best is None or res < best[1]:
            best = (W, res)
        if res < 1e3 * _eps(U.dtype) * max(k, 1):
            break
    return best


class RealStructure:
    r"""
    Real structure of a decomposition whose algebra is closed under entrywise complex conjugation (for
    example generated by real matrices), as returned by :meth:`Decomposition.real_structure`.

    Complex conjugation maps sector c onto a sector ``partner[c]``: :math:`\overline{V_c}=V_{d}(J_c\otimes M_c)`
    with :math:`d=` ``partner[c]`` and unitary :math:`J_c\in U(k_c)`, :math:`M_c\in U(m_c)` (course,
    Section 4.7). ``types[c]`` is

    * ``'R'`` (real type) if d = c and :math:`J_c\bar J_c=1`: the summand is :math:`M_{k_c}(\mathbb R)`;
    * ``'C'`` (complex type) if d != c: sectors c and d form one summand :math:`M_{k_c}(\mathbb C)` of the real
      algebra (realified: real dimension 2k_c);
    * ``'H'`` (quaternionic type) if d = c and :math:`J_c\bar J_c=-1`: the summand is :math:`M_{k_c/2}(\mathbb H)`
      (k_c and m_c are even).

    Attributes: ``types``, ``partner``, ``J``, ``M`` (lists over sectors), ``residuals`` (dict: 'leak' =
    weight of :math:`\overline{V_c}` outside sector d, 'conjugation' = relative distance of the conjugated
    generators from the algebra, 'kron' = distance of the conjugation block from
    :math:`J\otimes M`, 'sign' = :math:`\max\|J\bar J-\varepsilon\|`), ``tol`` and ``ok``.
    """

    def __init__(self, types, partner, J, M, residuals, tol):
        self.types = tuple(types)
        self.partner = tuple(partner)
        self.J, self.M = list(J), list(M)
        self.residuals = dict(residuals)
        self.tol = float(tol)
        self.ok = all(v <= self.tol for v in self.residuals.values())

    def __repr__(self) -> str:
        return f"RealStructure(types={self.types}, partner={self.partner}, ok={self.ok})"


class Decomposition:
    r"""
    Wedderburn decomposition :math:`V^*\mathcal AV=\bigoplus_cM_{k_c}\otimes1_{m_c}` of a von Neumann
    algebra :math:`\mathcal A\subseteq M_n(\mathbb C)`, as returned by :func:`wedderburn`.

    Attributes
    ----------
    V : (n, n) unitary. Column ``off_c + i * m_c + j`` (``off_c = sum_{d<c} k_d m_d``) is basis vector
        ``i < k_c`` (the *algebra index*) of copy ``j < m_c`` (the *multiplicity index*) of sector c, i.e.
        :math:`V(\bigoplus_c\mathbb C^{k_c}\otimes\mathbb C^{m_c})` in Kronecker order, so that
        ``V^* a V = blockdiag_c(kron(a_c, eye(m_c)))`` for a in A and
        ``V^* x V = blockdiag_c(kron(eye(k_c), x_c))`` for x in A'.
    k_factors : (k_c), sizes of the simple summands (dimensions of the irreducible representations).
    multiplicities : (m_c).
    algebra : TypeIAlgebra(k, k): the abstract algebra (+)_c M_{k_c}, on the device and in the precision
        of the decomposition.
    n, dims = (dim A, dim A') = (sum k_c^2, sum m_c^2), sector_dims = (k_c m_c).
    diagnostics : dict (attempts, refinement rounds, residuals, commutant method, ...).

    Sectors are sorted by (k_c, m_c). V is unique up to sector permutations and
    V -> V (+)_c (u_c (x) w_c) with unitary u_c in U(k_c), w_c in U(m_c).
    """

    def __init__(self, V: torch.Tensor, k_factors: Sequence[int], multiplicities: Sequence[int],
                 precision: str, diagnostics: Optional[Dict] = None):
        self.V = V
        self.k_factors = tuple(int(k) for k in k_factors)
        self.multiplicities = tuple(int(m) for m in multiplicities)
        if len(self.k_factors) != len(self.multiplicities):
            raise ValueError("one multiplicity per sector")
        self.n = V.shape[-1]
        if sum(k * m for k, m in zip(self.k_factors, self.multiplicities)) != self.n:
            raise ValueError("sum_c k_c m_c must equal n")
        self.precision = precision
        self.device = V.device
        self.dtype = V.dtype
        self.C = len(self.k_factors)
        self.algebra = TypeIAlgebra(list(self.k_factors), list(self.k_factors), complex_valued=True,
                                    precision=precision, device=V.device)
        self._commutant_algebra = None
        self._maps = {}
        self.diagnostics = dict(diagnostics or {})
        self._verify_data = None                 # generators, sampler, dim A', acceptance tol: set by wedderburn

    # ----- sizes -----
    @property
    def dim(self) -> int:
        """dim A = sum_c k_c^2."""
        return sum(k * k for k in self.k_factors)

    @property
    def commutant_dim(self) -> int:
        """dim A' = sum_c m_c^2."""
        return sum(m * m for m in self.multiplicities)

    @property
    def dims(self) -> Tuple[int, int]:
        """(dim A, dim A') = (sum_c k_c^2, sum_c m_c^2)."""
        return self.dim, self.commutant_dim

    @property
    def sector_dims(self) -> Tuple[int, ...]:
        """Dimensions k_c m_c of the sector subspaces (ranks of the central projections)."""
        return tuple(k * m for k, m in zip(self.k_factors, self.multiplicities))

    @property
    def offsets(self) -> Tuple[int, ...]:
        """First column of every sector in V."""
        out, o = [], 0
        for d in self.sector_dims:
            out.append(o)
            o += d
        return tuple(out)

    def commutant_algebra(self) -> TypeIAlgebra:
        """TypeIAlgebra(m, m): the abstract commutant (+)_c M_{m_c}."""
        if self._commutant_algebra is None:
            self._commutant_algebra = TypeIAlgebra(list(self.multiplicities), list(self.multiplicities),
                                                   complex_valued=True, precision=self.precision,
                                                   device=self.device)
        return self._commutant_algebra

    def __repr__(self) -> str:
        return (f"Decomposition(n={self.n}, k={self.k_factors}, m={self.multiplicities}, "
                f"dim A={self.dim}, dim A'={self.commutant_dim})")

    # ----- maps -----
    def _map(self, side: str):
        if side not in self._maps:
            pq, src, w = _sector_maps(self.k_factors, self.multiplicities, self.n, side, self.device)
            self._maps[side] = (pq, src, w.to(self.dtype))
        return self._maps[side]

    def _matrices(self, a, what: str) -> torch.Tensor:
        a = torch.as_tensor(a)
        if a.dim() == 2:
            a = a.unsqueeze(0)
        if a.dim() != 3 or tuple(a.shape[-2:]) != (self.n, self.n):
            raise ValueError(f"{what}: expected ({self.n}, {self.n}) or (batch, {self.n}, {self.n}), got {tuple(a.shape)}")
        return a.to(device=self.device, dtype=self.dtype)

    def _to_blocks(self, a, side: str) -> torch.Tensor:
        a = self._matrices(a, f"to_{side}")
        B, n = a.shape[0], self.n
        pq, src, w = self._map(side)
        smax = max(self.k_factors) if side == 'algebra' else max(self.multiplicities)
        b = (self.V.mH @ a @ self.V).reshape(B, n * n)
        out = torch.zeros(B, self.C * smax * smax, dtype=self.dtype, device=self.device)
        out.index_add_(1, src, b[:, pq] * w)
        return out.reshape(B, self.C, smax, smax)

    def _from_blocks(self, x, side: str, alg: TypeIAlgebra) -> torch.Tensor:
        if isinstance(x, Operator):
            if list(x.algebra.k_factors) != list(alg.k_factors):
                raise ValueError(f"from_{side}: operator of an algebra with blocks {x.algebra.k_factors}, "
                                 f"expected {alg.k_factors}")
            x = x.matrix
        x = torch.as_tensor(x)
        if x.dim() == 3:
            x = x.unsqueeze(0)
        smax = alg.k_max
        if tuple(x.shape[1:]) != (self.C, smax, smax):
            raise ValueError(f"from_{side}: expected (batch, {self.C}, {smax}, {smax}), got {tuple(x.shape)}")
        x = x.to(device=self.device, dtype=self.dtype)
        B, n = x.shape[0], self.n
        pq, src, _ = self._map(side)
        b = torch.zeros(B, n * n, dtype=self.dtype, device=self.device)
        b[:, pq] = x.reshape(B, -1)[:, src]
        return self.V @ b.reshape(B, n, n) @ self.V.mH

    def to_algebra(self, a: MatrixLike) -> Operator:
        r"""
        Blocks of matrices of A: a = V (+)_c (a_c (x) 1_{m_c}) V^*  ->  Operator with blocks a_c.

        a: (n, n) or (batch, n, n). Returns an Operator of ``self.algebra`` with batch size ``batch`` (1
        for a single matrix), storage (batch, C, k_max, k_max). Vectorised (two n x n products per
        matrix and one gather), no host synchronisation. For a matrix outside A the result is the block
        form of the trace-preserving conditional expectation E_A(a) (the copies are averaged:
        a_c = m_c^{-1} tr_{m_c}[(V^* a V)_{cc}]).
        """
        return self.algebra.operator(self._to_blocks(a, 'algebra'))

    def from_algebra(self, op: Union[Operator, torch.Tensor]) -> torch.Tensor:
        """
        Inverse of to_algebra: Operator (or tensor (batch, C, k_max, k_max)) -> matrices
        V (+)_c (a_c (x) 1_{m_c}) V^*, shape (batch, n, n). Vectorised, no host synchronisation.
        """
        return self._from_blocks(op, 'algebra', self.algebra)

    def to_commutant(self, x: MatrixLike) -> Operator:
        r"""
        Blocks of matrices of A': x = V (+)_c (1_{k_c} (x) x_c) V^*  ->  Operator of
        ``commutant_algebra()`` with blocks x_c (batch, C, m_max, m_max). Outside A' the result is the
        block form of E_{A'}(x) (x_c = k_c^{-1} tr_{k_c}[(V^* x V)_{cc}]).
        """
        return self.commutant_algebra().operator(self._to_blocks(x, 'commutant'))

    def from_commutant(self, op: Union[Operator, torch.Tensor]) -> torch.Tensor:
        """Inverse of to_commutant: blocks x_c -> V (+)_c (1_{k_c} (x) x_c) V^*, shape (batch, n, n)."""
        return self._from_blocks(op, 'commutant', self.commutant_algebra())

    def conditional_expectation(self, a: MatrixLike, onto: str = 'algebra') -> torch.Tensor:
        """
        The trace-preserving conditional expectation of M_n onto A (onto='algebra') or A'
        (onto='commutant'), i.e. the Hilbert-Schmidt orthogonal projection: (batch, n, n).
        For a finite group, E_{A'} is the twirl.
        """
        if onto == 'algebra':
            return self._from_blocks(self._to_blocks(a, 'algebra'), 'algebra', self.algebra)
        if onto == 'commutant':
            return self._from_blocks(self._to_blocks(a, 'commutant'), 'commutant', self.commutant_algebra())
        raise ValueError("onto must be 'algebra' or 'commutant'")

    def central_projections(self) -> torch.Tensor:
        """Minimal central projections P_c = V_c V_c^* of A (and of A'), shape (C, n, n)."""
        cols = torch.repeat_interleave(torch.arange(self.C, device=self.device),
                                       torch.tensor(self.sector_dims, device=self.device))
        mask = (cols[None, :] == torch.arange(self.C, device=self.device)[:, None]).to(self.dtype)
        return torch.einsum('ip,cp,jp->cij', self.V, mask, self.V.conj())

    def basis(self, which: str = 'algebra') -> torch.Tensor:
        """
        Hilbert-Schmidt orthonormal basis of A (which='algebra', sum k_c^2 elements
        V (E_ii' (x) 1_m) V^* / sqrt(m_c)) or of A' (which='commutant', sum m_c^2 elements
        V (1_k (x) E_jj') V^* / sqrt(k_c)); shape (dim, n, n).
        """
        if which == 'algebra':
            sizes, other, alg = self.k_factors, self.multiplicities, self.algebra
        elif which == 'commutant':
            sizes, other, alg = self.multiplicities, self.k_factors, self.commutant_algebra()
        else:
            raise ValueError("which must be 'algebra' or 'commutant'")
        smax = max(sizes)
        idx, scale = [], []
        for c, (s, o) in enumerate(zip(sizes, other)):
            ii, jj = torch.meshgrid(torch.arange(s), torch.arange(s), indexing='ij')
            idx.append((c * smax * smax + ii * smax + jj).flatten())
            scale += [o ** -0.5] * (s * s)
        idx = torch.cat(idx).to(self.device)
        D = idx.numel()
        x = torch.zeros(D, self.C * smax * smax, dtype=self.dtype, device=self.device)
        x[torch.arange(D, device=self.device), idx] = torch.tensor(scale, dtype=self.dtype, device=self.device)
        return self._from_blocks(x.reshape(D, self.C, smax, smax), which, alg)

    # ----- real structure -----
    def real_structure(self, tol: Optional[float] = None, seed: Optional[int] = 0) -> RealStructure:
        r"""
        Types (real, complex, quaternionic) of the simple summands of the *real* algebra, for an algebra
        closed under entrywise complex conjugation (generated by real matrices, or by a set closed under
        conjugation). See :class:`RealStructure` and course Section 4.7.

        :math:`\overline{V}=V\,P` with the unitary :math:`P=V^*\overline V`; because :math:`\bar a\in\mathcal A`
        for :math:`a\in\mathcal A`, P maps sector c onto one sector d and its block is :math:`J\otimes M` by
        Schur's lemma; for d = c, :math:`J\bar J=\varepsilon 1` with :math:`\varepsilon=\pm1`. The type is
        decided by the sign of :math:`\operatorname{tr}(J\bar J)/k`, which is :math:`\pm1` up to rounding
        (a gap of 2), and partners by the sector carrying the weight of :math:`\overline{V_c}`. Cost:
        one n x n product and an SVD of size k_c^2 x m_c^2 per sector.

        Raises ValueError if the algebra is not closed under conjugation (the conjugate of a sector is
        not, up to ``tol``, inside one sector of the same shape).
        """
        data = self._verify_data or {}
        tol = float(data.get('tol', _eps(self.dtype) ** 0.5) if tol is None else tol)
        gens = data.get('generators')
        conj_res = self._residual(gens.conj(), 'algebra') if gens is not None else 0.0
        if conj_res > tol:
            raise ValueError(f"real_structure: the conjugates of the generators are not in the algebra (residual "
                             f"{conj_res:.1e}); the algebra is not closed under complex conjugation")
        V = self.V if torch.is_complex(self.V) else self.V.to(torch.complex128)
        P = V.mH @ V.conj()
        offs, ks, ms = self.offsets, self.k_factors, self.multiplicities
        types, partner, Js, Ms = [], [], [], []
        leak = kron = sign = 0.0
        for c in range(self.C):
            k, m = ks[c], ms[c]
            col = P[:, offs[c]:offs[c] + k * m]
            w = torch.stack([col[offs[d]:offs[d] + ks[d] * ms[d]].abs().pow(2).sum() for d in range(self.C)])
            w = (w / (k * m)).tolist()
            d = max(range(self.C), key=lambda i: w[i])
            out = sum(w[i] for i in range(self.C) if i != d) ** 0.5
            if (ks[d], ms[d]) != (k, m) or out > tol:
                raise ValueError(f"real_structure: the conjugate of sector {c} is not a sector (weights {w}); "
                                 "the algebra is not closed under complex conjugation")
            leak = max(leak, out)
            B = P[offs[d]:offs[d] + k * m, offs[c]:offs[c] + k * m]
            R = B.reshape(k, m, k, m).permute(0, 2, 1, 3).reshape(k * k, m * m)
            U, S, Wh = torch.linalg.svd(R)
            J = U[:, 0].reshape(k, k) * k ** 0.5
            M = Wh[0].reshape(m, m) * (float(S[0]) / k ** 0.5)
            kron = max(kron, float(_fro(B - torch.kron(J, M))) / (k * m) ** 0.5)
            if kron > tol:
                raise ValueError(f"real_structure: conjugation is not of the form J (x) M on sector {c} "
                                 f"(residual {kron:.1e}); the algebra is not closed under complex conjugation")
            if d == c:
                eps_J = float((torch.trace(J @ J.conj()) / k).real)
                eps_M = float((torch.trace(M @ M.conj()) / m).real)
                e = 1.0 if eps_J > 0 else -1.0
                eye_k = torch.eye(k, dtype=J.dtype, device=J.device)
                eye_m = torch.eye(m, dtype=J.dtype, device=J.device)
                sign = max(sign, float(_fro(J @ J.conj() - e * eye_k)) / k ** 0.5,
                           float(_fro(M @ M.conj() - e * eye_m)) / m ** 0.5)
                if e < 0 and (k % 2 or m % 2):
                    sign = max(sign, 1.0)                  # impossible for exact input: J conj(J) = -1 needs k even
                types.append('R' if e > 0 else 'H')
            else:
                types.append('C')
            partner.append(d)
            Js.append(J)
            Ms.append(M)
        for c, d in enumerate(partner):
            if partner[d] != c:
                raise ValueError(f"real_structure: conjugation pairs sector {c} with {d} but {d} with {partner[d]}")
        return RealStructure(types, partner, Js, Ms, dict(conjugation=conj_res, leak=leak, kron=kron, sign=sign), tol)

    def real_basis(self, tol: Optional[float] = None, seed: Optional[int] = 0) -> Tuple[torch.Tensor, List[Dict]]:
        r"""
        Real orthogonal matrix O (n x n, real dtype) adapted to the real algebra (course, Section 4.7):

        * real sector c: columns :math:`V_c(W_J\otimes W_M)` with :math:`J=W_JW_J^T`, :math:`M=W_MW_M^T`
          (Takagi), so that :math:`O_c^TaO_c=\alpha_c\otimes1_{m_c}` with a *real* :math:`\alpha_c\in M_{k_c}(\mathbb R)`;
        * complex pair (c, d): columns :math:`\sqrt2\,\mathrm{Re}\,V_c` then :math:`\sqrt2\,\mathrm{Im}\,V_c`, so that
          :math:`O^TaO=\begin{pmatrix}\mathrm{Re}\,x&\mathrm{Im}\,x\\-\mathrm{Im}\,x&\mathrm{Re}\,x\end{pmatrix}` with :math:`x=a_c\otimes1_{m_c}`;
        * quaternionic sector c: columns :math:`V_cW` with :math:`J\otimes M=WW^T` (a real basis of the sector).

        Returns (O, blocks) with one dict per block: type, sectors, columns (slice). Raises ValueError if
        the algebra is not closed under conjugation.
        """
        rs = self.real_structure(tol)
        gen = _rng(seed, self.device)
        V = self.V if torch.is_complex(self.V) else self.V.to(torch.complex128)
        offs, ks, ms = self.offsets, self.k_factors, self.multiplicities
        cols, blocks, start, takagi = [], [], 0, 0.0
        for c in range(self.C):
            k, m, d, t = ks[c], ms[c], rs.partner[c], rs.types[c]
            Vc = V[:, offs[c]:offs[c] + k * m]
            if t == 'C':
                if d < c:
                    continue
                Q = torch.cat([Vc.real, Vc.imag], dim=1) * 2 ** 0.5
                sectors = (c, d)
            else:
                if t == 'R':
                    WJ, rJ = _takagi_unitary(rs.J[c], gen)
                    WM, rM = _takagi_unitary(rs.M[c], gen)
                    W, r = torch.kron(WJ, WM), max(rJ, rM)
                else:
                    W, r = _takagi_unitary(torch.kron(rs.J[c], rs.M[c]), gen)
                takagi = max(takagi, r)
                X = Vc @ W
                takagi = max(takagi, float(_fro(X.imag)) / (k * m) ** 0.5)
                Q, sectors = X.real, (c,)
            cols.append(Q)
            blocks.append(dict(type=t, sectors=sectors, columns=slice(start, start + Q.shape[1])))
            start += Q.shape[1]
        O = torch.cat(cols, dim=1)
        if takagi > max(rs.tol, 1e3 * _eps(self.dtype) * self.n):
            warnings.warn(f"real_basis: Takagi residual {takagi:.1e}", DecompositionWarning)
        return O, blocks

    # ----- verification -----
    def _residual(self, a: torch.Tensor, side: str) -> float:
        """max over the batch of ||a - E(a)||_F / ||a||_F for the conditional expectation onto one side."""
        a = self._matrices(a, 'verify')
        e = self.conditional_expectation(a, 'algebra' if side == 'algebra' else 'commutant')
        nrm = _fro(a)
        r = _fro(a - e) / torch.where(nrm > 0, nrm, torch.ones_like(nrm))
        return float(r.max()) if r.numel() else 0.0

    def verify(self, tol: Optional[float] = None, generators: Optional[MatrixLike] = None,
               commutant: Optional[MatrixLike] = None, n_samples: int = 2) -> Dict:
        r"""
        Residuals of the decomposition (relative Frobenius norms):

        * 'unitarity': max |V^* V - 1|;
        * 'algebra': max_j ||S_j - E_A(S_j)|| / ||S_j|| over the generators (those given to
          :func:`wedderburn`, or ``generators``): zero iff V^* S_j V = (+)_c s_c (x) 1_{m_c};
        * 'commutant': the same for elements of A' (``commutant``, or ``n_samples`` fresh random
          elements of the commutant used by the decomposition): zero iff V^* X V = (+)_c 1 (x) x_c;
        * 'commutant_dim': (dim A' from the commutant basis or the characters, sum_c m_c^2).

        Together these certify A = V((+)_c M_{k_c} (x) 1_{m_c})V^* (module docstring). Returns the dict
        with 'ok' = all residuals <= tol and the dimensions equal; default tol: the acceptance threshold of the
        decomposition, max(sqrt(eps), 1e3 * noise of the commutant samples) (= sqrt(eps) for well-conditioned input).
        """
        data = self._verify_data or {}
        if tol is None:
            tol = data.get('tol', _eps(self.dtype) ** 0.5)
        tol = float(tol)
        eye = torch.eye(self.n, dtype=self.dtype, device=self.device)
        out = dict(unitarity=float((self.V.mH @ self.V - eye).abs().amax()))
        gens = generators if generators is not None else data.get('generators')
        out['algebra'] = self._residual(_stack(gens), 'algebra') if gens is not None else None
        if commutant is not None:
            comm = _stack(commutant, "commutant")
        elif data.get('sampler') is not None:
            sampler = data['sampler']
            comm = torch.stack([sampler.general() for _ in range(n_samples)])
        else:
            comm = None
        out['commutant'] = self._residual(comm, 'commutant') if comm is not None else None
        out['commutant_dim'] = (data.get('commutant_dim'), self.commutant_dim)
        ok = out['unitarity'] <= tol
        ok &= out['algebra'] is None or out['algebra'] <= tol
        ok &= out['commutant'] is None or out['commutant'] <= tol
        ok &= data.get('commutant_dim') is None or data['commutant_dim'] == self.commutant_dim
        out['ok'] = bool(ok)
        out['tol'] = tol
        return out


def _thresholds(eps: float, n: int, noise: float) -> Dict[str, float]:
    """
    Decision thresholds of the randomised algorithm. noise: estimated relative error of the commutant samples
    (n eps for a twirl or a given basis; for a null-space basis also the neglected singular values and the
    perturbation eps sigma_max / sigma_kept_min of the null space). See 'Tolerances' in the module docstring.
    """
    nu = max(n * eps, noise)
    small = max(eps ** 0.5, 1e3 * nu)
    return dict(cluster=eps ** 0.25, floor=1e3 * nu, small=small, polar=max(eps ** 0.25, 10 * small))


def _irreducible_subspaces(sampler, th: Dict[str, float], n: int, max_rounds: int, diag: Dict) -> List[torch.Tensor]:
    """
    Orthonormal bases (n, d_i) of irreducible invariant subspaces whose sum is C^n: eigenspaces of a random
    Hermitian K in A', each split further by the eigenspaces of compressions of fresh random elements
    until the compressed commutant is scalar (irreducibility).
    """
    K = sampler.hermitian()
    w, Q = torch.linalg.eigh(K)
    pending = [Q[:, s:e] for s, e in _gap_clusters(w, th['cluster'], th['floor'])]
    diag['initial_clusters'] = len(pending)
    final = []
    for rnd in range(max_rounds):
        if not pending:
            diag['refinement_rounds'] = rnd
            return final
        Y = sampler.hermitian()
        nxt = []
        for Qc in pending:
            d = Qc.shape[1]
            Z = Qc.mH @ Y @ Qc
            Z = (Z + Z.mH) / 2
            dev = float(_fro(Z - torch.diagonal(Z).mean() * torch.eye(d, dtype=Z.dtype, device=Z.device)))
            if dev <= th['small']:
                final.append(Qc)
                continue
            w2, U2 = torch.linalg.eigh(Z)
            nxt += [Qc @ U2[:, s:e] for s, e in _gap_clusters(w2, th['cluster'], th['floor'])]
        pending = nxt
    raise _Retry(f"could not split {len(pending)} invariant subspace(s) into irreducible ones in {max_rounds} "
                 "rounds (degenerate random elements of the commutant)")


def _decompose_once(sampler, n: int, dtype, device, th: Dict[str, float], max_rounds: int,
                    precision: str) -> Decomposition:
    diag = {}
    subs = _irreducible_subspaces(sampler, th, n, max_rounds, diag)
    M = len(subs)
    dims = [Q.shape[1] for Q in subs]
    Qall = torch.cat(subs, dim=1)
    offs = [0]
    for d in dims:
        offs.append(offs[-1] + d)
    Y = sampler.general()
    Z = Qall.mH @ Y @ Qall
    # norms of the intertwiner blocks between subspaces of equal dimension (zero otherwise)
    norms = [[0.0] * M for _ in range(M)]
    blocks = {}
    for d in sorted(set(dims)):
        mem = [i for i in range(M) if dims[i] == d]
        if len(mem) < 2:
            continue
        idx = torch.tensor([list(range(offs[i], offs[i + 1])) for i in mem], device=device)   # (r, d)
        T = Z[idx[:, None, :, None], idx[None, :, None, :]]                                   # (r, r, d, d)
        nr = _fro(T).tolist()
        for a, i in enumerate(mem):
            for b, j in enumerate(mem):
                if i != j:
                    norms[i][j] = nr[a][b]
                    blocks[(i, j)] = T[a, b]
    # equivalence classes: connected components of the graph of non-zero intertwiners
    thr = th['small']
    parent = list(range(M))

    def find(i):
        while parent[i] != i:
            parent[i] = parent[parent[i]]
            i = parent[i]
        return i
    for i in range(M):
        for j in range(i + 1, M):
            if norms[i][j] > thr or norms[j][i] > thr:
                parent[find(i)] = find(j)
    classes = {}
    for i in range(M):
        classes.setdefault(find(i), []).append(i)
    # align the copies of every class (Prim: largest intertwiner first), Q_j' = Q_j polar(W_i^* T_ij)^*
    sectors = []
    for mem in classes.values():
        k = dims[mem[0]]
        W = {mem[0]: torch.eye(k, dtype=dtype, device=device)}
        order = [mem[0]]
        rest = set(mem[1:])
        while rest:
            i, j = max(((i, j) for i in order for j in rest), key=lambda p: norms[p[0]][p[1]])
            T = W[i].mH @ blocks[(i, j)]
            A, s, Bh = torch.linalg.svd(T)
            if float(s[-1]) < (1 - th['polar']) * float(s[0]):
                raise _Retry("an intertwiner between equivalent subspaces is not a multiple of a unitary")
            W[j] = Bh.mH @ A.mH
            order.append(j)
            rest.discard(j)
        cols = torch.stack([subs[j] @ W[j] for j in order])          # (m, n, k): copy j, vector i
        sectors.append((k, len(order), cols.permute(1, 2, 0).reshape(n, k * len(order))))
    sectors.sort(key=lambda t: (t[0], t[1]))
    V = torch.cat([c for _, _, c in sectors], dim=1)
    diag['irreducible_subspaces'] = M
    return Decomposition(V, [k for k, _, _ in sectors], [m for _, m, _ in sectors], precision, diag)


def wedderburn(generators: MatrixLike, *, group: bool = False, method: str = 'random', seed: Optional[int] = 0,
               tol: Optional[float] = None, precision: Optional[str] = None, device=None,
               commutant: Optional[MatrixLike] = None, max_tries: int = 3, max_rounds: int = 30) -> Decomposition:
    r"""
    Wedderburn decomposition of the von Neumann algebra generated by matrices (module docstring).

    generators: (J, n, n) tensor or list of (n, n) matrices. Any matrices: the generated algebra is the
        unital *-algebra of S and S^* (S'' by the double commutant theorem), so non-*-closed input is
        closed automatically. Lie algebra generators of a connected compact group (Hermitian or
        anti-Hermitian) generate the same algebra as the group.
    group: True if ``generators`` are *all* elements of a unitary representation of a finite group:
        the commutant is then sampled by the twirl (O(|G| n^3) per sample, no commutant basis), and
        dim A' is taken from the characters.
    method: 'random' (Murota-Kanno-Kojima-Kojima; the only method).
    seed: seed of the random elements (default 0: reproducible); None for fresh entropy. The sectors and
        the subspaces do not depend on it, V only up to the unitary freedom (+)_c u_c (x) w_c.
    tol: null-space threshold of the commutant (see commutant_basis); default sqrt(eps).
    precision: 'double' (complex128, default) or 'single' (complex64; default for float32/complex64
        input; tolerances scale with eps, residuals ~1e-6).
    device: device of the computation and of the result (default: that of the input).
    commutant: optional precomputed basis (d, n, n) of A' (linearly independent, e.g. from commutant_basis);
        d is used as dim A' in the verification.
    max_tries: independent random draws before DecompositionError; max_rounds: splitting rounds per draw.

    Returns a verified :class:`Decomposition`; ``diagnostics`` records attempts, rounds and residuals.
    Cost: commutant (see commutant_basis) + O(n^3) per random element + O(J n^3) verification.
    """
    if method != 'random':
        raise ValueError("method must be 'random' (randomised algorithm of Murota et al.)")
    S0 = _stack(generators)
    precision, dtype = _work_dtype(S0, precision)
    device = S0.device if device is None else torch.device(device)
    S = S0.to(device=device, dtype=dtype)
    n = S.shape[-1]
    eps = _eps(dtype)
    tol = eps ** 0.5 if tol is None else float(tol)
    gen = _rng(seed, device)
    info = {}
    if commutant is not None:
        basis = _stack(commutant, "commutant").to(device=device, dtype=dtype)
        sampler, dim_c = _BasisSampler(basis, gen), basis.shape[0]
        noise = n * eps
        info['commutant_method'] = 'given'
    elif group:
        _check_unitary_group(S, tol)
        dim_c = commutant_dimension(S)
        sampler = _TwirlSampler(S, gen, dim_c)
        noise = n * eps
        X = sampler.general()
        err = float(_fro(S @ X - X @ S).max())          # X has unit norm
        if err > tol:
            raise ValueError(f"group=True: the twirl does not commute with the matrices (residual {err:.1e}); "
                             "they are not all elements of a finite group (closed under products)")
        info['commutant_method'] = 'twirl'
    else:
        basis, cinfo = _nullspace_commutant(_hermitian_parts(S, tol), tol, gen, n, dtype, device)
        sampler, dim_c = _BasisSampler(basis, gen), basis.shape[0]
        scale = max(1.0, cinfo.get('sigma_max') or 0.0)
        noise = max((cinfo.get('sigma_null_max') or 0.0) / scale,             # neglected commutators
                    eps * scale / cinfo.get('sigma_kept_min', float('inf')))  # perturbation of the null space
        info['commutant_method'] = 'nullspace'
        info['commutant_info'] = cinfo
    info['commutant_dim'] = dim_c
    th = _thresholds(eps, n, noise)
    info['thresholds'] = th
    failures = []
    for attempt in range(1, max_tries + 1):
        try:
            dec = _decompose_once(sampler, n, dtype, device, th, max_rounds, precision)
        except _Retry as e:
            failures.append(str(e))
            continue
        dec._verify_data = dict(generators=S, sampler=sampler, commutant_dim=dim_c, tol=th['small'])
        res = dec.verify()
        if res['ok']:
            dec.diagnostics.update(info)
            dec.diagnostics.update(attempts=attempt, residuals=res, seed=seed, precision=precision,
                                   failures=failures)
            return dec
        failures.append(f"verification failed: {res}")
    raise DecompositionError(f"no verified decomposition in {max_tries} random draws (n={n}, dim A'={dim_c}); "
                             f"failures: {failures}. Possible causes: an ill-conditioned commutant (try another "
                             "tol), a group that is not closed or not unitary, or input of insufficient precision.")


def from_group(elements: MatrixLike, **kwargs) -> Decomposition:
    r"""
    Decomposition of :math:`\pi(G)''` for a unitary representation of a finite group given by all its
    elements (|G|, n, n): ``wedderburn(elements, group=True, **kwargs)``. Then
    :math:`V^*\pi(g)V=\bigoplus_c\rho_c(g)\otimes1_{m_c}` with the inequivalent irreducible
    representations :math:`\rho_c` (``to_algebra(elements)``) of dimensions k_c and multiplicities m_c
    (course, Proposition 2.7).
    """
    return wedderburn(elements, group=True, **kwargs)


def from_generators(generators: MatrixLike, **kwargs) -> Decomposition:
    """
    Decomposition of the von Neumann algebra generated by arbitrary matrices (e.g. Lie algebra generators
    of a compact group, or generators of a finite group): ``wedderburn(generators, group=False, **kwargs)``.
    """
    return wedderburn(generators, group=False, **kwargs)


