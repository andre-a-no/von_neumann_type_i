def _stack(mats: MatrixLike, what: str = "generators") -> torch.Tensor:
    """A tensor (J, n, n) from a tensor (n, n) / (J, n, n) or a sequence of (n, n) matrices."""
    if isinstance(mats, torch.Tensor):
        t = mats
    else:
        mats = [torch.as_tensor(m) for m in mats]
        if not mats:
            raise ValueError(f"{what}: empty list (give at least one matrix, e.g. the identity)")
        dev = mats[0].device
        t = torch.stack([m.to(dev) for m in mats])
    if t.dim() == 2:
        t = t.unsqueeze(0)
    if t.dim() != 3 or t.shape[-1] != t.shape[-2] or t.shape[0] == 0:
        raise ValueError(f"{what}: expected square matrices (n, n) or a stack (J, n, n), got {tuple(t.shape)}")
    return t


def _work_dtype(t: torch.Tensor, precision: Optional[str]) -> Tuple[str, torch.dtype]:
    if precision is None:
        precision = 'single' if t.dtype in (torch.float32, torch.complex64, torch.float16, torch.bfloat16) \
            else 'double'
    if precision not in ('single', 'double'):
        raise ValueError("precision must be 'single' or 'double'")
    return precision, (torch.complex64 if precision == 'single' else torch.complex128)


def _eps(dtype: torch.dtype) -> float:
    """Machine epsilon of a floating or complex dtype."""
    return torch.finfo({torch.complex64: torch.float32, torch.complex128: torch.float64}.get(dtype, dtype)).eps


def _fro(x: torch.Tensor) -> torch.Tensor:
    """Frobenius norms over the last two axes."""
    return torch.linalg.vector_norm(x, dim=(-2, -1))


def _normalised(x: torch.Tensor) -> torch.Tensor:
    nrm = _fro(x)
    return x / torch.where(nrm > 0, nrm, torch.ones_like(nrm))[..., None, None]


def _hermitian_parts(S: torch.Tensor, tol: float) -> torch.Tensor:
    """
    Hermitian generators of the same *-algebra (and the same commutant): the parts (S + S^*)/2 and
    (S - S^*)/(2i) of every S_j, normalised to unit Frobenius norm; parts of relative size below tol
    are rounding noise and dropped. Returns (J', n, n), possibly with J' = 0.
    """
    H = torch.cat([(S + S.mH) / 2, (S - S.mH) / 2j])
    scale = torch.cat([_fro(S), _fro(S)])
    keep = (_fro(H) > tol * scale).tolist()
    H = H[[i for i, k in enumerate(keep) if k]]
    return _normalised(H)


def _gap_clusters(w: torch.Tensor, rel: float, floor: float) -> List[Tuple[int, int]]:
    """
    Clusters of sorted real eigenvalues w (ascending): consecutive values whose gap is at most
    max(rel * spread, floor * max|w|) stay together. Returns index ranges [(start, end), ...].
    """
    n = w.numel()
    if n <= 1:
        return [(0, n)]
    spread = w[-1] - w[0]
    thr = torch.maximum(rel * spread, floor * w.abs().max())
    cuts = ((w[1:] - w[:-1]) > thr).nonzero().flatten().tolist()
    bounds = [0] + [c + 1 for c in cuts] + [n]
    return list(zip(bounds[:-1], bounds[1:]))


def _rng(seed: Optional[int], device) -> torch.Generator:
    g = torch.Generator(device=device)
    if seed is None:
        g.seed()
    else:
        g.manual_seed(int(seed))
    return g


def _randn(shape, dtype, device, gen):
    return torch.randn(*shape, dtype=dtype, device=device, generator=gen)


