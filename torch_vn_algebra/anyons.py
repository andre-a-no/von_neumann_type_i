"""
Chains of SU(2)_k anyons in the fusion-path basis: Temperley-Lieb algebras as Type I algebras.

L spin-1/2 anyons of SU(2)_k (k >= 2) fuse along a path of charges a_0, a_1, ..., a_L with a_{i+1} = a_i +- 1 in
{0, .., k} (twice the spin: a path on the Dynkin diagram A_{k+1}). The Temperley-Lieb generators act on the charge
between two anyons,

    (e_i)_{a', a} = [a_{i-1} = a_{i+1} = c] sqrt(S_a S_a') / S_c,   a = a_i, a' = a_i' = c +- 1,
    S_a = sin((a+1) pi/(k+2)),

and satisfy e_i^2 = d e_i, e_i e_{i+-1} e_i = e_i and e_i e_j = e_j e_i for |i - j| > 1, with d = 2 cos(pi/(k+2)), the
quantum dimension of the anyon; e_i/d is the projector onto the trivial fusion channel of anyons i and i+1.

Open chain (a_0 = 0): the last charge b = a_L, the total charge of the chain, labels the sectors, and the algebra
generated by the e_i (the Temperley-Lieb algebra TL_L(d) modulo the Jones-Wenzl ideal) is (+)_b M_{n_b}, n_b the
number of paths from 0 to b: a TypeIAlgebra. The paths of sector b are ordered by their previous charge, so that
TL_{L-1} c TL_L is in the standard form of inclusions.Inclusion (AnyonChain.inclusion): its Bratteli diagram is
A_{k+1}, its index tends to d^2 = 4 cos^2(pi/(k+2)) and its Markov trace weights the sectors by the quantum dimensions
(Jones' subfactors). Periodic chain: closed paths a_0 = a_L with L generators; one sector (no symmetry resolution).

H = -J sum_i e_i. For J > 0 it is the critical RSOS chain whose continuum limit is the unitary minimal model with
central charge c = 1 - 6/((k+1)(k+2)) (k = 2: Ising, k = 3: tricritical Ising, c = 7/10, the golden chain of Fibonacci
anyons) and velocity v = pi sin(gamma)/gamma, gamma = pi/(k+2); with the boundary charges 0 and b the open chain has the
spectrum of the Kac character chi_{1,b+1}. These are checked in tests/test_anyons.py and scripts/anyon_chain.py.

    chain = AnyonChain(k=3, L=12)                       # sectors b = 0, 2 (even L)
    H = chain.hamiltonian()                             # dense Operator (+)_b H_b
    E = chain.low_energies(levels=2)                    # per sector; Lanczos for large sectors
    inc = chain.inclusion(); inc.index()                # TL_11 c TL_12, Jones index d^2 = phi^2 for k = 3
"""
import math
import warnings
from typing import Dict, List, Optional, Tuple

import torch

from . import cost, krylov
from .algebra import TypeIAlgebra

Operator = TypeIAlgebra.Operator

__all__ = ['AnyonChain']


class _Deflated:
    """H + shift * sum_j |psi_j><psi_j| as a matvec object for krylov.ground_state (excited states)."""

    def __init__(self, H, vectors: List[torch.Tensor], shift: float):
        self.H, self.vectors, self.shift = H, vectors, shift
        self.batch_size, self.dim, self.dtype, self.device = H.batch_size, H.dim, H.dtype, H.device

    def matvec(self, V):
        out = self.H.matvec(V)
        for psi in self.vectors:
            p = psi.to(V.dtype)
            if V.dim() == 2:
                out = out + self.shift * (p.conj() * V).sum(-1, keepdim=True) * p
            else:
                out = out + self.shift * torch.einsum('bk,bkm->bm', p.conj(), V).unsqueeze(1) * p.unsqueeze(-1)
        return out


class AnyonChain:
    """
    L spin-1/2 anyons of SU(2)_k in the fusion-path basis (see the module docstring). Attributes: k, L, periodic,
    d (quantum dimension), charges (2 x spin of the sectors), paths (one list of tuples per sector), algebra.
    """

    def __init__(self, k: int, L: int, periodic: bool = False, precision: str = 'double',
                 device: Optional[torch.device] = None):
        if k < 2:
            raise ValueError("AnyonChain: need k >= 2 (k = 1 has a single path)")
        if L < (3 if periodic else 2):
            raise ValueError("AnyonChain: need L >= 2 (open) or L >= 3 (periodic)")
        self.k, self.L, self.periodic = int(k), int(L), bool(periodic)
        self.d = 2 * math.cos(math.pi / (k + 2))
        if periodic:
            paths = [self._closed_paths()]
            self.charges = [None]
        else:
            P = self._open_paths(self.k, self.L)
            self.charges = sorted(P)
            paths = [P[b] for b in self.charges]
        self.paths = paths
        sizes = [len(p) for p in paths]
        cost.check_memory(cost.tensor_bytes((len(sizes), 2 * max(sizes)), torch.float64), 'cpu',
                          f"AnyonChain paths (k={k}, L={L}, {sum(sizes)} states)")
        self.algebra = TypeIAlgebra(sizes, sizes, precision=precision, device=device,
                                    charges=[None if b is None else b / 2 for b in self.charges])
        self._index = [{p: j for j, p in enumerate(ps)} for ps in paths]
        self._terms = None

    # ------------------------------------------------------------------ paths
    @staticmethod
    def _open_paths(k: int, L: int) -> Dict[int, List[Tuple[int, ...]]]:
        P = {0: [(0,)]}
        for _ in range(L):
            Q = {}
            for b in range(k + 1):
                out = []
                for c in (b - 1, b + 1):                      # previous charge ascending: standard form
                    if c in P:
                        out += [p + (b,) for p in P[c]]
                if out:
                    Q[b] = out
            P = Q
        return P

    def _closed_paths(self) -> List[Tuple[int, ...]]:
        k, L = self.k, self.L
        out = []

        def rec(p):
            if len(p) == L:
                if abs(p[-1] - p[0]) == 1:
                    out.append(tuple(p))
                return
            for a in (p[-1] - 1, p[-1] + 1):
                if 0 <= a <= k:
                    rec(p + [a])
        for a0 in range(k + 1):
            rec([a0])
        return out

    def quantum_dimension(self, a: int) -> float:
        """d_a = S_a / S_0 for the charge a (twice the spin): 1 for a = 0, d for a = 1."""
        return math.sin((a + 1) * math.pi / (self.k + 2)) / math.sin(math.pi / (self.k + 2))

    @property
    def n_generators(self) -> int:
        return self.L if self.periodic else self.L - 1

    def _generator_entries(self, i: int):
        """Entries (sector, row, col, value) of e_i (1 <= i <= n_generators)."""
        k = self.k
        S = [math.sin((a + 1) * math.pi / (k + 2)) for a in range(k + 1)]
        out = []
        for s, ps in enumerate(self.paths):
            idx = self._index[s]
            for j, p in enumerate(ps):
                if self.periodic:
                    pos, left, right = i % self.L, p[(i - 1) % self.L], p[(i + 1) % self.L]
                else:
                    pos, left, right = i, p[i - 1], p[i + 1]
                if left != right:
                    continue
                for a2 in (left - 1, left + 1):
                    if 0 <= a2 <= k:
                        q = p[:pos] + (a2,) + p[pos + 1:]
                        out.append((s, idx[q], j, math.sqrt(S[p[pos]] * S[a2]) / S[left]))
        return out

    def _all_terms(self):
        if self._terms is None:
            self._terms = [self._generator_entries(i) for i in range(1, self.n_generators + 1)]
        return self._terms

    # ------------------------------------------------------------------ operators
    def _dense(self, entries) -> Operator:
        alg = self.algebra
        cost.check_memory(cost.tensor_bytes((1, alg.C, alg.k_max, alg.k_max), alg.dtype), alg.hilbert.device,
                          f"AnyonChain dense operator ({alg.C} sectors up to {alg.k_max}); use sparse_hamiltonian")
        m = torch.zeros(1, alg.C, alg.k_max, alg.k_max, dtype=alg.dtype, device=alg.hilbert.device)
        if entries:
            s, r, c, v = zip(*entries)
            m.index_put_((torch.zeros(len(s), dtype=torch.long), torch.tensor(s), torch.tensor(r), torch.tensor(c)),
                         torch.tensor(v, dtype=torch.float64).to(m.dtype), accumulate=True)
        return alg.operator(m, is_self_adjoint=True)

    def generator(self, i: int) -> Operator:
        """The Temperley-Lieb generator e_i, 1 <= i <= L - 1 (open) or L (periodic), as a dense Operator."""
        if not 1 <= i <= self.n_generators:
            raise ValueError(f"generator: i must lie in 1..{self.n_generators}")
        op = self._dense(self._all_terms()[i - 1])
        op._is_positive = True
        return op

    def hamiltonian(self, J: float = 1.0) -> Operator:
        """H = -J sum_i e_i as a dense Operator (+)_b H_b."""
        entries = [(s, r, c, -J * v) for terms in self._all_terms() for (s, r, c, v) in terms]
        return self._dense(entries)

    def sparse_hamiltonian(self, J: float = 1.0) -> List[krylov.SparseSectorHamiltonian]:
        """H_b = -J sum_i e_i for every sector, as krylov.SparseSectorHamiltonian (batch 1; diagonal + sparse)."""
        alg = self.algebra
        dev, rdt = alg.hilbert.device, alg.hilbert.real_dtype
        out = []
        for s, n in enumerate(alg.k_factors):
            diag = torch.zeros(1, n, dtype=rdt, device=dev)
            rows, cols, vals = [], [], []
            for terms in self._all_terms():
                for (t, r, c, v) in terms:
                    if t != s:
                        continue
                    if r == c:
                        diag[0, r] -= J * v
                    else:
                        rows.append(r); cols.append(c); vals.append(-J * v)
            off = None
            if rows:
                with warnings.catch_warnings():               # PyTorch 2.x: note on disabled invariant checks
                    warnings.simplefilter('ignore', UserWarning)
                    off = torch.sparse_coo_tensor(torch.tensor([rows, cols], device=dev),
                                                  torch.tensor(vals, dtype=rdt, device=dev), (n, n))
            out.append(krylov.SparseSectorHamiltonian(diag, off, rdt))
        return out

    def low_energies(self, J: float = 1.0, levels: int = 1, dense_max: int = 1500, m: int = 120,
                     tol: Optional[float] = None) -> List[torch.Tensor]:
        """
        The `levels` lowest eigenvalues of H_b in every sector (ascending; fewer if the sector is smaller): dense
        eigvalsh for sectors up to dense_max, otherwise restarted Lanczos (krylov.ground_state) with deflation.
        """
        res = []
        sparse = None
        for s, n in enumerate(self.algebra.k_factors):
            lv = min(levels, n)
            if n <= dense_max:
                if sparse is None:
                    sparse = self.sparse_hamiltonian(J)
                w = torch.linalg.eigvalsh(sparse[s].to_dense()[0])
                res.append(w[:lv])
                continue
            if sparse is None:
                sparse = self.sparse_hamiltonian(J)
            H = sparse[s]
            shift = 4.0 * abs(J) * self.d * self.n_generators + 1.0
            vecs, es = [], []
            g = torch.Generator().manual_seed(s)
            for _ in range(lv):
                op = _Deflated(H, vecs, shift) if vecs else H
                E, psi, _ = krylov.ground_state(op, m=m, tol=tol, generator=g)
                es.append(E[0])
                vecs.append(psi)
            res.append(torch.stack(es))
        return res

    # ------------------------------------------------------------------ the tower
    def inclusion(self):
        """TL_{L-1} c TL_L as an inclusions.Inclusion in standard form (open chains, L >= 3): the matrix of the
        Bratteli diagram A_{k+1}, Lambda_{bc} = 1 if |b - c| = 1."""
        from .inclusions import Inclusion
        if self.periodic or self.L < 3:
            raise ValueError("inclusion: needs an open chain with L >= 3")
        prev = AnyonChain(self.k, self.L - 1, precision=self.algebra.precision, device=self.algebra.hilbert.device)
        lam = [[1 if abs(b - c) == 1 else 0 for c in prev.charges] for b in self.charges]
        inc = Inclusion(prev.algebra, self.algebra, lam, validate=False)
        inc.smaller = prev
        return inc

    # ------------------------------------------------------------------ conformal data
    @staticmethod
    def central_charge(k: int) -> float:
        """c = 1 - 6/((k+1)(k+2)) of the critical chain (J > 0)."""
        return 1 - 6 / ((k + 1) * (k + 2))

    @staticmethod
    def velocity(k: int) -> float:
        """v = pi sin(gamma)/gamma, gamma = pi/(k+2), for H = -sum_i e_i."""
        g = math.pi / (k + 2)
        return math.pi * math.sin(g) / g

    @staticmethod
    def kac(k: int, r: int, s: int) -> float:
        """Kac dimension h_{r,s} of the minimal model with m = k + 1: ((r(m+1) - s m)^2 - 1)/(4 m (m+1))."""
        m = k + 1
        return ((r * (m + 1) - s * m) ** 2 - 1) / (4 * m * (m + 1))

    def __repr__(self) -> str:
        kind = 'periodic' if self.periodic else 'open'
        return (f"AnyonChain(k={self.k}, L={self.L}, {kind}, d={self.d:.6f}, sectors={self.charges}, "
                f"sizes={self.algebra.k_factors})")
