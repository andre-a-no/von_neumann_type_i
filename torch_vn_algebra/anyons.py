"""
Chains of SU(2)_k anyons in the fusion-path basis: Temperley-Lieb algebras as Type I algebras.

L spin-1/2 anyons of SU(2)_k (k >= 2) fuse along a path of charges a_0, a_1, ..., a_L with a_{i+1} = a_i +- 1 in
{0, .., k} (twice the spin: a path on the Dynkin diagram A_{k+1}). The Temperley-Lieb generators act on the charge
between two anyons,

    (e_i)_{a', a} = [a_{i-1} = a_{i+1} = c] sqrt(S_a S_a') / S_c,   a = a_i, a' = a_i' = c +- 1,
    S_a = sin((a+1) pi/(k+2)),

and satisfy e_i^2 = d e_i, e_i e_{i+-1} e_i = e_i and e_i e_j = e_j e_i for |i - j| > 1, with d = 2 cos(pi/(k+2)), the
quantum dimension of the anyon; e_i/d is the projector onto the trivial fusion channel of anyons i and i+1.

Open chain (a_0 = 0): the last charge b = a_L, the total charge of the chain, labels the sectors (algebra charges = b,
twice the spin, as in su2.SU2Chain), and the algebra generated by the e_i (the Temperley-Lieb algebra TL_L(d) modulo
the Jones-Wenzl ideal) is (+)_b M_{n_b}, n_b the number of paths from 0 to b: a TypeIAlgebra. The paths of sector b
are ordered by their previous charge, so that TL_{L-1} c TL_L is in the standard form of inclusions.Inclusion
(AnyonChain.inclusion). Its Bratteli diagram is A_{k+1}; for L >= k (when all charges of both parities occur) its
index is d^2 = 4 cos^2(pi/(k+2)), its Markov trace weights the sectors by the quantum dimensions, and its basic
construction has the block sizes of TL_{L+1} (Jones' subfactors). Periodic chain (L even; A_{k+1} is bipartite):
closed paths a_0 = a_L with L generators; the generators keep the parity of a_0, so there are two sectors (charges 0
and 1 = parity of a_0) with the same spectrum (translation by one site exchanges them).

H = -J sum_i e_i. For J > 0 it is the critical RSOS chain whose continuum limit is the unitary minimal model with
central charge c = 1 - 6/((k+1)(k+2)) (k = 2: Ising; k = 3: tricritical Ising, c = 7/10, equivalent to the golden
chain of Fibonacci anyons; k = 4: tetracritical Ising) and velocity v = pi sin(gamma)/gamma, gamma = pi/(k+2); with
the boundary charges 0 and b the open chain has the spectrum of the Kac character chi_{1,b+1}. These are checked in
tests/test_anyons.py and scripts/anyon_chain.py.

    chain = AnyonChain(k=3, L=12)                       # sectors b = 0, 2 (even L)
    H = chain.hamiltonian()                             # dense Operator (+)_b H_b
    E = chain.low_energies(levels=2)                    # per sector; Lanczos for large sectors
    inc = chain.inclusion(); inc.index()                # TL_11 c TL_12, Jones index d^2 = phi^2 for k = 3
"""
import math
import warnings
from typing import List, Optional

import numpy as np
import torch

from . import cost, krylov
from .algebra import TypeIAlgebra

Operator = TypeIAlgebra.Operator

__all__ = ['AnyonChain']


class AnyonChain:
    """
    L spin-1/2 anyons of SU(2)_k in the fusion-path basis (see the module docstring). Attributes: k, L, periodic,
    d (quantum dimension), charges (sector labels: 2 x total spin, or the parity of a_0 for periodic chains), paths
    (one int8 array (n_b, L+1) per sector, or (n_b, L) for periodic chains: a_0, .., a_{L-1}), algebra.
    """

    def __init__(self, k: int, L: int, periodic: bool = False, precision: str = 'double',
                 device: Optional[torch.device] = None):
        if k < 2:
            raise ValueError("AnyonChain: need k >= 2 (k = 1 has a single path)")
        if L < (4 if periodic else 2):
            raise ValueError("AnyonChain: need L >= 2 (open) or L >= 4 (periodic)")
        if periodic and L % 2:
            raise ValueError("AnyonChain: periodic chains need even L (A_{k+1} is bipartite: no closed paths of "
                             "odd length)")
        self.k, self.L, self.periodic = int(k), int(L), bool(periodic)
        self.d = 2 * math.cos(math.pi / (k + 2))
        npos = L if periodic else L + 1
        est = int((k + 1) * self.d ** L) + 1              # number of states: paths grow like d^L (Perron-Frobenius)
        cost.check_memory(est * (npos + 8 * (4 * L + 8)), 'cpu', f"AnyonChain (k={k}, L={L}): paths and generators")
        if periodic:
            allp = self._closed_paths(self.k, self.L)
            par = allp[:, 0] % 2
            self.charges = [c for c in (0, 1) if (par == c).any()]
            self.paths = [allp[par == c] for c in self.charges]
        else:
            P = self._open_paths(self.k, self.L)
            self.charges = sorted(P)
            self.paths = [P[b] for b in self.charges]
        sizes = [len(p) for p in self.paths]
        self.algebra = TypeIAlgebra(sizes, sizes, precision=precision, device=device, charges=list(self.charges))
        self._base = (k + 1) ** np.arange(npos, dtype=np.int64) if (k + 1) ** npos < 2 ** 62 else None
        self._lookup = [self._make_lookup(p) for p in self.paths]
        self._terms = None

    # ------------------------------------------------------------------ paths
    @staticmethod
    def _open_paths(k: int, L: int):
        """{b: int8 array (n_b, L+1)}, rows grouped by the previous charge in ascending order (standard form)."""
        P = {0: np.zeros((1, 1), dtype=np.int8)}
        for _ in range(L):
            Q = {}
            for b in range(k + 1):
                parts = [np.concatenate([P[c], np.full((len(P[c]), 1), b, dtype=np.int8)], axis=1)
                         for c in (b - 1, b + 1) if c in P]
                if parts:
                    Q[b] = np.concatenate(parts, axis=0)
            P = Q
        return P

    @staticmethod
    def _closed_paths(k: int, L: int) -> np.ndarray:
        """All closed walks a_0, .., a_{L-1} on A_{k+1} (a_L = a_0), int8 array (n, L)."""
        W = np.arange(k + 1, dtype=np.int8)[:, None]
        for _ in range(L - 1):
            last = W[:, -1:]
            parts = []
            for step in (-1, 1):
                nxt = last + step
                ok = ((nxt >= 0) & (nxt <= k))[:, 0]
                parts.append(np.concatenate([W[ok], nxt[ok]], axis=1))
            W = np.concatenate(parts, axis=0)
        return W[np.abs(W[:, -1].astype(np.int64) - W[:, 0]) == 1]

    def _codes(self, paths: np.ndarray):
        if self._base is not None:
            return paths.astype(np.int64) @ self._base
        return [p.tobytes() for p in paths]

    def _make_lookup(self, paths: np.ndarray):
        codes = self._codes(paths)
        if self._base is not None:
            order = np.argsort(codes, kind='stable')
            return codes, order, codes[order]
        return {c: j for j, c in enumerate(codes)}, None, None

    def _find(self, s: int, targets: np.ndarray) -> np.ndarray:
        codes, order, sorted_codes = self._lookup[s]
        if order is not None:
            t = targets.astype(np.int64) @ self._base
            return order[np.searchsorted(sorted_codes, t)]
        return np.array([codes[p.tobytes()] for p in targets], dtype=np.int64)

    def quantum_dimension(self, a: int) -> float:
        """d_a = S_a / S_0 for the charge a (twice the spin): 1 for a = 0, d for a = 1."""
        return math.sin((a + 1) * math.pi / (self.k + 2)) / math.sin(math.pi / (self.k + 2))

    @property
    def n_generators(self) -> int:
        return self.L if self.periodic else self.L - 1

    def _generator_entries(self, i: int):
        """Entries of e_i (1 <= i <= n_generators) as numpy arrays (sector, row, col, value)."""
        k = self.k
        S = np.sin((np.arange(k + 1) + 1) * np.pi / (k + 2))
        out = [], [], [], []
        for s, A in enumerate(self.paths):
            if self.periodic:
                pos, left, right = i % self.L, A[:, (i - 1) % self.L], A[:, (i + 1) % self.L]
            else:
                pos, left, right = i, A[:, i - 1], A[:, i + 1]
            cur = A[:, pos].astype(np.int64)
            for step in (-1, 1):
                a2 = left.astype(np.int64) + step
                ok = (left == right) & (a2 >= 0) & (a2 <= k)
                cols = np.nonzero(ok)[0]
                if not len(cols):
                    continue
                tgt = A[cols].copy()
                tgt[:, pos] = a2[cols]
                rows = self._find(s, tgt)
                vals = np.sqrt(S[cur[cols]] * S[a2[cols]]) / S[left[cols].astype(np.int64)]
                for lst, x in zip(out, (np.full(len(cols), s), rows, cols, vals)):
                    lst.append(x)
        return tuple(np.concatenate(x) if x else np.zeros(0) for x in out)

    def _all_terms(self):
        if self._terms is None:
            self._terms = [self._generator_entries(i) for i in range(1, self.n_generators + 1)]
        return self._terms

    # ------------------------------------------------------------------ operators
    def _dense(self, s, r, c, v) -> Operator:
        alg = self.algebra
        cost.check_memory(alg.bytes_per_operator(1), alg.hilbert.device,
                          f"AnyonChain dense operator ({alg.C} sectors up to {alg.k_max}); use sparse_hamiltonian")
        dev = alg.hilbert.device
        flat = torch.zeros(1, alg._flat_size(), dtype=alg.dtype, device=dev)     # the blocks, in the algebra's layout
        if len(s):
            s, r, c = [torch.as_tensor(np.asarray(x, dtype=np.int64), device=dev) for x in (s, r, c)]
            k = torch.tensor(alg.k_factors, dtype=torch.long, device=dev)
            pos = alg._flat_offsets()[s] + r * (k[s] if alg._packed else alg.k_max) + c
            flat.index_put_((torch.zeros_like(pos), pos),
                            torch.as_tensor(np.asarray(v, dtype=np.float64), device=dev).to(flat.dtype), accumulate=True)
        slabs = alg._unflatten(flat)
        return Operator(alg, is_self_adjoint=True, **(dict(parts=slabs) if alg._packed else dict(matrix=slabs[0])))

    def generator(self, i: int) -> Operator:
        """The Temperley-Lieb generator e_i, 1 <= i <= L - 1 (open) or L (periodic), as a dense Operator."""
        if not 1 <= i <= self.n_generators:
            raise ValueError(f"generator: i must lie in 1..{self.n_generators}")
        op = self._dense(*self._all_terms()[i - 1])
        op._is_positive = True
        return op

    def _summed(self, J: float):
        terms = self._all_terms()
        s, r, c, v = (np.concatenate([t[j] for t in terms]) for j in range(4))
        return s.astype(np.int64), r.astype(np.int64), c.astype(np.int64), -J * v

    def hamiltonian(self, J: float = 1.0) -> Operator:
        """H = -J sum_i e_i as a dense Operator (+)_b H_b."""
        return self._dense(*self._summed(J))

    def sparse_hamiltonian(self, J: float = 1.0) -> List[krylov.SparseSectorHamiltonian]:
        """H_b = -J sum_i e_i for every sector, as krylov.SparseSectorHamiltonian (batch 1; diagonal + sparse)."""
        alg = self.algebra
        dev, rdt = alg.hilbert.device, alg.hilbert.real_dtype
        S, R, Cc, V = self._summed(J)
        out = []
        for s, n in enumerate(alg.k_factors):
            sel = S == s
            r, c, v = R[sel], Cc[sel], V[sel]
            dg = np.zeros(n)
            on = r == c
            np.add.at(dg, r[on], v[on])
            diag = torch.as_tensor(dg, dtype=rdt, device=dev).unsqueeze(0)
            off = None
            if (~on).any():
                with warnings.catch_warnings():               # PyTorch 2.x: note on disabled invariant checks
                    warnings.simplefilter('ignore', UserWarning)
                    off = torch.sparse_coo_tensor(torch.as_tensor(np.stack([r[~on], c[~on]]), device=dev),
                                                  torch.as_tensor(v[~on], dtype=rdt, device=dev), (n, n))
            out.append(krylov.SparseSectorHamiltonian(diag, off, rdt))
        return out

    def low_energies(self, J: float = 1.0, levels: int = 1, dense_max: int = 1500, m: int = 120,
                     tol: Optional[float] = None) -> List[torch.Tensor]:
        """
        The `levels` lowest eigenvalues of H_b in every sector (ascending; fewer if the sector is smaller): dense
        eigvalsh for sectors up to dense_max, otherwise restarted Lanczos (krylov.ground_state) with deflation.
        """
        res = []
        sparse = None
        for s, n in enumerate(self.algebra.k_factors):
            lv = min(levels, n)
            if n <= dense_max:
                if sparse is None:
                    sparse = self.sparse_hamiltonian(J)
                w = torch.linalg.eigvalsh(sparse[s].to_dense()[0])
                res.append(w[:lv])
                continue
            if sparse is None:
                sparse = self.sparse_hamiltonian(J)
            H = sparse[s]
            shift = 4.0 * abs(J) * self.d * self.n_generators + 1.0
            vecs, es = [], []
            g = torch.Generator().manual_seed(s)
            for _ in range(lv):
                op = krylov.Deflated(H, vecs, shift) if vecs else H
                E, psi, _ = krylov.ground_state(op, m=m, tol=tol, generator=g)
                es.append(E[0])
                vecs.append(psi)
            res.append(torch.stack(es))
        return res

    # ------------------------------------------------------------------ the tower
    def inclusion(self):
        """TL_{L-1} c TL_L as an inclusions.Inclusion in standard form (open chains, L >= 3): the matrix of the
        Bratteli diagram A_{k+1}, Lambda_{bc} = 1 if |b - c| = 1."""
        from .inclusions import Inclusion
        if self.periodic or self.L < 3:
            raise ValueError("inclusion: needs an open chain with L >= 3")
        prev = AnyonChain(self.k, self.L - 1, precision=self.algebra.precision, device=self.algebra.hilbert.device)
        lam = [[1 if abs(b - c) == 1 else 0 for c in prev.charges] for b in self.charges]
        inc = Inclusion(prev.algebra, self.algebra, lam, validate=False)
        inc.smaller = prev
        return inc

    # ------------------------------------------------------------------ conformal data
    @staticmethod
    def central_charge(k: int) -> float:
        """c = 1 - 6/((k+1)(k+2)) of the critical chain (J > 0)."""
        return 1 - 6 / ((k + 1) * (k + 2))

    @staticmethod
    def velocity(k: int) -> float:
        """v = pi sin(gamma)/gamma, gamma = pi/(k+2), for H = -sum_i e_i."""
        g = math.pi / (k + 2)
        return math.pi * math.sin(g) / g

    @staticmethod
    def kac(k: int, r: int, s: int) -> float:
        """Kac dimension h_{r,s} of the minimal model with m = k + 1: ((r(m+1) - s m)^2 - 1)/(4 m (m+1))."""
        m = k + 1
        return ((r * (m + 1) - s * m) ** 2 - 1) / (4 * m * (m + 1))

    def __repr__(self) -> str:
        kind = 'periodic' if self.periodic else 'open'
        return (f"AnyonChain(k={self.k}, L={self.L}, {kind}, d={self.d:.6f}, sectors={self.charges}, "
                f"sizes={self.algebra.k_factors})")
