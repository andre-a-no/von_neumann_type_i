#!/usr/bin/env python3
"""
Example: Schur-Weyl duality on four spins 1/2, computed from the symmetries alone.

The symmetric group S_4 permutes the four tensor factors of (C^2)^{(x)4}; SU(2) acts diagonally, generated by
the total spin S_x, S_y, S_z. torch_vn_algebra.decompose computes the von Neumann algebras generated by each
set of matrices and their Wedderburn decompositions V^* A V = (+)_c M_{k_c} (x) 1_{m_c}. Schur-Weyl duality
(Fulton-Harris, Sec. 6.1) predicts that the two algebras are each other's commutants: the same sectors, labelled
by the total spin J (the Casimir S^2 = J(J+1) is central in both), with k and m exchanged:

    S_4:   k_c = dimension of the irrep of the partition (2 + J, 2 - J),  m_c = 2J + 1
    SU(2): k_c = 2J + 1,                                                  m_c = the same S_4 dimension.
"""
import math
import time

import torch

import torch_vn_algebra.decompose as dc

L = 4


def main():
    t0 = time.time()
    perms = dc.permutation_representation(L, 2)              # all 24 elements of S_4 on C^16
    spin = dc.total_spin(L)                                   # (S_x, S_y, S_z), generators of su(2)
    S2 = sum(s @ s for s in spin)

    D_perm = dc.from_group(perms)                            # pi(S_4)''   (commutant by the twirl)
    D_spin = dc.from_generators(spin)                         # SU(2)''     (commutant by the null space)

    print(f"(C^2)^(x){L}: n = {D_perm.n}")
    for name, D in (("S_4 (permutations)", D_perm), ("SU(2) (total spin)", D_spin)):
        # S^2 lies in both algebras and is central: its block in sector c is J(J+1) 1
        blocks = D.to_algebra(S2).matrix[0]
        J = [(-1 + math.sqrt(1 + 4 * float(blocks[c, 0, 0].real))) / 2 for c in range(D.C)]
        res = D.diagnostics['residuals']
        print(f"\n{name}: dim A = {D.dim}, dim A' = {D.commutant_dim}, "
              f"residuals {max(res['algebra'], res['commutant']):.1e}")
        print(f"  {'J':>4s} {'partition':>10s} {'k_c':>4s} {'m_c':>4s}")
        for c in sorted(range(D.C), key=lambda c: -J[c]):
            j = round(J[c])
            print(f"  {j:4d} {str((L // 2 + j, L // 2 - j)):>10s} {D.k_factors[c]:4d} {D.multiplicities[c]:4d}")

    swap = sorted(zip(D_perm.k_factors, D_perm.multiplicities)) == \
        sorted(zip(D_spin.multiplicities, D_spin.k_factors))
    same_centre = all(min(float(torch.linalg.matrix_norm(P - Q)) for Q in D_spin.central_projections()) < 1e-10
                      for P in D_perm.central_projections())
    print(f"\nk and m exchanged: {swap}; same central projections: {same_centre}; "
          f"time {time.time() - t0:.2f} s")


if __name__ == '__main__':
    main()
